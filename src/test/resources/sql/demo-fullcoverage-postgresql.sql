-- quickvo全类型覆盖验证(pgvector容器):json/jsonb/vector/bytea/时间类型/生成列/序列/分区/外键/视图
CREATE EXTENSION IF NOT EXISTS vector;

DROP SCHEMA IF EXISTS quickvo_demo CASCADE;
CREATE SCHEMA quickvo_demo;

CREATE TABLE quickvo_demo.QUICKVO_DEMO_STAFF (
  STAFF_ID varchar(32) NOT NULL,
  STAFF_CODE varchar(20) NOT NULL,
  STAFF_NAME varchar(60) NOT NULL,
  SEX smallint DEFAULT 1,
  BIRTHDAY date,
  ENTRY_DATE timestamp(6),
  SALARY numeric(10,2),
  STATUS char(1) DEFAULT '1',
  REMARK text,
  IS_DELETED boolean DEFAULT false,
  CONSTRAINT PK_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_STAFF_CODE UNIQUE (STAFF_CODE)
);
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_STAFF IS '员工信息表';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.STAFF_CODE IS '员工工号';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.STAFF_NAME IS '员工姓名';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.SEX IS '性别:1男;2女';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.BIRTHDAY IS '生日';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.ENTRY_DATE IS '入职时间';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.SALARY IS '薪资';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.STATUS IS '状态:1在职;2离职';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.REMARK IS '备注';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_STAFF.IS_DELETED IS '是否删除';

-- 全类型矩阵
CREATE TABLE quickvo_demo.QUICKVO_DEMO_TYPE_MATRIX (
  ID bigserial NOT NULL,
  COL_CHAR char(10),
  COL_VARCHAR varchar(200),
  COL_TEXT text,
  COL_SMALLINT smallint,
  COL_INT integer,
  COL_BIGINT bigint,
  COL_OID oid,
  COL_DECIMAL numeric(18,6),
  COL_REAL real,
  COL_DOUBLE double precision,
  COL_BOOLEAN boolean,
  COL_DATE date,
  COL_TIME time(6),
  COL_TIMETZ timetz,
  COL_TIMESTAMP timestamp(6),
  COL_TIMESTAMPTZ timestamptz,
  COL_INTERVAL interval,
  COL_BYTEA bytea,
  COL_JSON json,
  COL_JSONB jsonb,
  COL_UUID uuid,
  COL_VECTOR vector(3),
  COL_AMOUNT numeric(10,2),
  COL_VIRTUAL numeric(10,2) GENERATED ALWAYS AS (round(COL_AMOUNT * 1.1, 2)) STORED,
  CONSTRAINT PK_TYPE_MATRIX PRIMARY KEY (ID)
);
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_TYPE_MATRIX IS '全类型矩阵表';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_TYPE_MATRIX.COL_JSON IS 'JSON字段';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_TYPE_MATRIX.COL_JSONB IS 'JSONB字段';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_TYPE_MATRIX.COL_VECTOR IS '向量字段';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_TYPE_MATRIX.COL_VIRTUAL IS '生成列';

-- 序列默认值主键(数据库优先→identity,无需配置)
CREATE SEQUENCE quickvo_demo.SEQ_QUICKVO_DEMO_SEQ_BILL;
CREATE TABLE quickvo_demo.QUICKVO_DEMO_SEQ_BILL (
  BILL_ID bigint NOT NULL DEFAULT nextval('quickvo_demo.seq_quickvo_demo_seq_bill'::regclass),
  BILL_NO varchar(32),
  BILL_AMOUNT numeric(12,2),
  CONSTRAINT PK_SEQ_BILL PRIMARY KEY (BILL_ID)
);
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_SEQ_BILL IS '序列默认值主键表';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_SEQ_BILL.BILL_ID IS '账单ID(序列)';

-- 复合主键 + 外键
CREATE TABLE quickvo_demo.QUICKVO_DEMO_ORDER (
  ORDER_ID varchar(32) NOT NULL,
  ORDER_LINE int NOT NULL,
  STAFF_ID varchar(32) NOT NULL REFERENCES quickvo_demo.QUICKVO_DEMO_STAFF (STAFF_ID),
  AMOUNT numeric(12,4) NOT NULL DEFAULT 0,
  PRICE numeric(12,4) NOT NULL DEFAULT 0,
  TOTAL_AMT numeric(18,2),
  CREATE_TIME timestamp NOT NULL DEFAULT now(),
  CONSTRAINT PK_DEMO_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE)
);
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_ORDER IS '订单明细表';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_ORDER.ORDER_ID IS '订单号';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_ORDER.ORDER_LINE IS '订单行号';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_ORDER.CREATE_TIME IS '创建时间';

-- 分区表(分区键纳入主键→辅助主键)
CREATE TABLE quickvo_demo.QUICKVO_DEMO_TRADE (
  TRADE_ID varchar(32) NOT NULL,
  TRADE_DATE date NOT NULL,
  AMOUNT numeric(12,2),
  CONSTRAINT PK_DEMO_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)
) PARTITION BY RANGE (TRADE_DATE);
CREATE TABLE quickvo_demo.QUICKVO_DEMO_TRADE_202601 PARTITION OF quickvo_demo.QUICKVO_DEMO_TRADE
  FOR VALUES FROM ('2026-01-01') TO ('2026-02-01');
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_TRADE IS '交易流水表(按月分区)';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_TRADE.TRADE_ID IS '交易ID';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_TRADE.TRADE_DATE IS '交易日期';

CREATE TABLE quickvo_demo.QUICKVO_DEMO_STAFF_LOG (
  LOG_ID varchar(32) NOT NULL,
  STAFF_ID varchar(32) NOT NULL REFERENCES quickvo_demo.QUICKVO_DEMO_STAFF (STAFF_ID),
  OPERATE varchar(50) NOT NULL,
  OPERATE_TIME timestamp NOT NULL,
  CONSTRAINT PK_DEMO_STAFF_LOG PRIMARY KEY (LOG_ID)
);
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_STAFF_LOG IS '员工操作日志表';

CREATE OR REPLACE VIEW quickvo_demo.QUICKVO_DEMO_V_STAFF AS
SELECT STAFF_ID, STAFF_CODE, STAFF_NAME, SEX, STATUS FROM quickvo_demo.QUICKVO_DEMO_STAFF;

-- 特殊符号备注表(pg):双引号/反斜杠/javadoc终结符/多行注释
CREATE TABLE quickvo_demo.QUICKVO_DEMO_SPECIAL_NOTE (
  NOTE_ID varchar(32) NOT NULL,
  QUOTE_NOTE varchar(50),
  SLASH_NOTE varchar(50),
  MULTI_LINE text,
  CONSTRAINT PK_SPECIAL_NOTE PRIMARY KEY (NOTE_ID)
);
COMMENT ON TABLE quickvo_demo.QUICKVO_DEMO_SPECIAL_NOTE IS '特殊符号"备注\/"表:含*/与反斜杠';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_SPECIAL_NOTE.NOTE_ID IS '主键ID';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_SPECIAL_NOTE.QUOTE_NOTE IS '含双引号"和单引号''测试';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_SPECIAL_NOTE.SLASH_NOTE IS '含反斜杠\与正斜杠/和*/终结符';
COMMENT ON COLUMN quickvo_demo.QUICKVO_DEMO_SPECIAL_NOTE.MULTI_LINE IS E'第一行说明
第二行说明(应归一为空格)';
