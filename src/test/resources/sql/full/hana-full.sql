-- SAP HANA 全场景覆盖DDL(39041/HXE;identity原生;注释用COMMENT ON)
DROP TABLE QS_SALES;
DROP TABLE QS_LOG;
DROP TABLE QS_TRADE;
DROP TABLE QS_PRODUCT;
DROP TABLE QS_ORDER;
DROP TABLE QS_STAFF;

CREATE TABLE QS_STAFF (
  STAFF_ID NVARCHAR(32) NOT NULL,
  STAFF_CODE NVARCHAR(20) NOT NULL,
  STAFF_NAME NVARCHAR(60) NOT NULL,
  SEX INTEGER DEFAULT 1,
  BIRTHDAY DATE,
  ENTRY_TIME TIMESTAMP,
  SALARY DECIMAL(10,2),
  STATUS NVARCHAR(1) DEFAULT 'A',
  BIG_REMARK NCLOB,
  PHOTO BLOB,
  BONUS DECIMAL(10,2) DEFAULT 0,
  TOTAL_PAY DECIMAL(10,2) GENERATED ALWAYS AS (SALARY + BONUS),
  CREATE_TIME TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LAST_MODIFIED TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_QS_CODE UNIQUE (STAFF_CODE)
);
CREATE INDEX IDX_QS_NAME ON QS_STAFF (STAFF_NAME);
CREATE INDEX IDX_QS_SALARY ON QS_STAFF (SALARY);
COMMENT ON TABLE QS_STAFF IS '员工信息表';
COMMENT ON COLUMN QS_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN QS_STAFF.STAFF_CODE IS '员工工号';
COMMENT ON COLUMN QS_STAFF.STAFF_NAME IS '员工姓名';
COMMENT ON COLUMN QS_STAFF.SEX IS '性别:1男2女';
COMMENT ON COLUMN QS_STAFF.SALARY IS '薪资';
COMMENT ON COLUMN QS_STAFF.BIG_REMARK IS '大文本备注(CLOB场景)';
COMMENT ON COLUMN QS_STAFF.PHOTO IS '照片二进制(BLOB场景)';
COMMENT ON COLUMN QS_STAFF.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN QS_STAFF.LAST_MODIFIED IS '最后修改时间';

CREATE TABLE QS_ORDER (
  ORDER_ID NVARCHAR(32) NOT NULL,
  ORDER_LINE INTEGER NOT NULL,
  STAFF_ID NVARCHAR(32) NOT NULL,
  AMOUNT DECIMAL(12,4) NOT NULL DEFAULT 0,
  PRICE DECIMAL(12,4) NOT NULL DEFAULT 0,
  CREATE_TIME TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QS_ORDER_STAFF FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE QS_ORDER IS '订单明细表';
COMMENT ON COLUMN QS_ORDER.ORDER_ID IS '订单号';
COMMENT ON COLUMN QS_ORDER.ORDER_LINE IS '订单行号';

CREATE TABLE QS_PRODUCT (
  ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  PRODUCT_NAME NVARCHAR(100) NOT NULL,
  PRODUCT_TYPE INTEGER DEFAULT 1,
  WEIGHT DOUBLE,
  SCORE DECIMAL(3,1) DEFAULT 0.0,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_PRODUCT PRIMARY KEY (ID)
);
COMMENT ON TABLE QS_PRODUCT IS '产品表';
COMMENT ON COLUMN QS_PRODUCT.ID IS '产品ID';
COMMENT ON COLUMN QS_PRODUCT.PRODUCT_NAME IS '产品名称';

CREATE TABLE QS_TRADE (
  TRADE_ID NVARCHAR(32) NOT NULL,
  TRADE_DATE DATE NOT NULL,
  AMOUNT DECIMAL(12,2),
  STATUS INTEGER DEFAULT 0,
  CONSTRAINT PK_QS_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)
) PARTITION BY HASH (TRADE_ID) PARTITIONS 2;
COMMENT ON TABLE QS_TRADE IS '交易流水表';
COMMENT ON COLUMN QS_TRADE.TRADE_ID IS '交易ID';
COMMENT ON COLUMN QS_TRADE.TRADE_DATE IS '交易日期';

CREATE TABLE QS_LOG (
  LOG_ID NVARCHAR(32) NOT NULL,
  STAFF_ID NVARCHAR(32) NOT NULL,
  ACTION NVARCHAR(50) NOT NULL,
  ACTION_TIME TIMESTAMP NOT NULL,
  CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QS_LOG_STAFF FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE QS_LOG IS '操作日志表';
COMMENT ON COLUMN QS_LOG.LOG_ID IS '日志ID';
COMMENT ON COLUMN QS_LOG.ACTION IS '操作';

CREATE TABLE QS_SALES (
  DOC_ID BIGINT NOT NULL,
  SALE_DATE DATE NOT NULL,
  AMOUNT DECIMAL(18,2),
  CONSTRAINT PK_QS_SALES PRIMARY KEY (DOC_ID, SALE_DATE)
) PARTITION BY RANGE (SALE_DATE) (
  PARTITION '2024-01-01' <= VALUES < '2025-01-01',
  PARTITION '2025-01-01' <= VALUES < '2026-01-01',
  PARTITION OTHERS
);
COMMENT ON TABLE QS_SALES IS '销售表(HANA RANGE分区)';
COMMENT ON COLUMN QS_SALES.SALE_DATE IS '销售日期(分区键)';
