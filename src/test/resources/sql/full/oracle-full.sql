WHENEVER SQLERROR CONTINUE
ALTER SESSION SET CONTAINER=FREEPDB1;
-- JSON/VECTOR columns require an ASSM tablespace; the SYSTEM tablespace is non-ASSM, so point the
-- system user's default at USERS. The round-trip DDL omits TABLESPACE, so qs_staff (JSON) would
-- otherwise fail with ORA-43853 when recreated from the generated DDL.
ALTER USER system DEFAULT TABLESPACE USERS;
WHENEVER SQLERROR CONTINUE
BEGIN EXECUTE IMMEDIATE 'DROP VIEW SYSTEM.QS_V_STAFF'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SYSTEM.QS_TRADE CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SYSTEM.QS_LOG CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SYSTEM.QS_ORDER CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SYSTEM.QS_PRODUCT CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SYSTEM.QS_STAFF CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE SYSTEM.SEQ_QS_TRADE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE SYSTEM.QS_STAFF (
  STAFF_ID varchar2(32) NOT NULL,
  STAFF_CODE varchar2(20) NOT NULL,
  STAFF_NAME varchar2(60) NOT NULL,
  SEX number(3) DEFAULT 1,
  BIRTHDAY date,
  ENTRY_TIME timestamp(6),
  SALARY number(10,2),
  STATUS char(1) DEFAULT 'A',
  BIG_REMARK clob,
  PHOTO blob,
  EXT_INFO json,
  EMBEDDING vector(3),
  BONUS number(10,2) DEFAULT 0,
  TOTAL_PAY number(10,2) GENERATED ALWAYS AS (SALARY + BONUS) STORED,
  CREATE_TIME timestamp DEFAULT SYSTIMESTAMP,
  LAST_MODIFIED timestamp DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_QS_CODE UNIQUE (STAFF_CODE)
) TABLESPACE SYSAUX;
CREATE INDEX IDX_QS_NAME ON SYSTEM.QS_STAFF (STAFF_NAME);
CREATE INDEX IDX_QS_SAL ON SYSTEM.QS_STAFF (SALARY);
COMMENT ON TABLE SYSTEM.QS_STAFF IS '员工信息表';
COMMENT ON COLUMN SYSTEM.QS_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN SYSTEM.QS_STAFF.BIG_REMARK IS '大文本';
COMMENT ON COLUMN SYSTEM.QS_STAFF.PHOTO IS '照片';
COMMENT ON COLUMN SYSTEM.QS_STAFF.EMBEDDING IS '向量';

CREATE TABLE SYSTEM.QS_ORDER (
  ORDER_ID varchar2(32) NOT NULL,
  ORDER_LINE number(9) NOT NULL,
  STAFF_ID varchar2(32) NOT NULL,
  AMOUNT number(12,4) DEFAULT 0,
  CREATE_TIME timestamp DEFAULT SYSDATE,
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QS_ORD_STAFF FOREIGN KEY (STAFF_ID) REFERENCES SYSTEM.QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE SYSTEM.QS_ORDER IS '订单明细表';

CREATE TABLE SYSTEM.QS_PRODUCT (
  ID number(19) GENERATED ALWAYS AS IDENTITY NOT NULL,
  PRODUCT_NAME varchar2(100) NOT NULL,
  PRODUCT_TYPE number(5) DEFAULT 1,
  WEIGHT binary_double,
  CREATED_AT timestamp(3) DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_QS_PROD PRIMARY KEY (ID)
) TABLESPACE SYSAUX;
COMMENT ON TABLE SYSTEM.QS_PRODUCT IS '产品表';

CREATE SEQUENCE SYSTEM.SEQ_QS_TRADE;
CREATE TABLE SYSTEM.QS_TRADE (
  TRADE_ID number(19) DEFAULT SYSTEM.SEQ_QS_TRADE.NEXTVAL NOT NULL,
  TRADE_DATE date NOT NULL,
  AMOUNT number(12,2),
  STATUS number(3) DEFAULT 0,
  CONSTRAINT PK_QS_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)
) PARTITION BY RANGE (TRADE_DATE) (
  PARTITION P202601 VALUES LESS THAN (TO_DATE('2026-02-01','YYYY-MM-DD')),
  PARTITION P202602 VALUES LESS THAN (TO_DATE('2026-03-01','YYYY-MM-DD')),
  PARTITION PMAX VALUES LESS THAN (MAXVALUE)
) TABLESPACE SYSAUX;
COMMENT ON TABLE SYSTEM.QS_TRADE IS '交易流水表';

CREATE TABLE SYSTEM.QS_LOG (
  LOG_ID varchar2(32) NOT NULL,
  STAFF_ID varchar2(32) NOT NULL,
  ACTION varchar2(50) NOT NULL,
  ACTION_TIME timestamp NOT NULL,
  CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QS_LOG_STAFF FOREIGN KEY (STAFF_ID) REFERENCES SYSTEM.QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE SYSTEM.QS_LOG IS '操作日志表';
EXIT;
