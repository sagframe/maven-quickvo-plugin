DROP SCHEMA IF EXISTS quickvo_demo CASCADE;
CREATE SCHEMA quickvo_demo;
CREATE TABLE quickvo_demo.QS_STAFF (
  STAFF_ID varchar(32) NOT NULL, STAFF_CODE varchar(20) NOT NULL, STAFF_NAME varchar(60) NOT NULL,
  SEX int DEFAULT 1, BIRTHDAY date, ENTRY_TIME timestamp(6), SALARY numeric(10,2),
  STATUS char(1) DEFAULT 'A', BIG_REMARK text, PHOTO bytea, EXT_INFO json,
  BONUS numeric(10,2) DEFAULT 0, TOTAL_PAY numeric(10,2) GENERATED ALWAYS AS (SALARY + BONUS) STORED,
  CREATE_TIME timestamp NOT NULL DEFAULT now(), LAST_MODIFIED timestamp NOT NULL DEFAULT now(),
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID), CONSTRAINT UK_QS_CODE UNIQUE (STAFF_CODE)
);
CREATE INDEX IDX_QS_NAME ON quickvo_demo.QS_STAFF (STAFF_NAME);
COMMENT ON TABLE quickvo_demo.QS_STAFF IS '员工信息表';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.STAFF_ID IS '员工ID';
CREATE TABLE quickvo_demo.QS_ORDER (
  ORDER_ID varchar(32) NOT NULL, ORDER_LINE int NOT NULL, STAFF_ID varchar(32) NOT NULL REFERENCES quickvo_demo.QS_STAFF (STAFF_ID),
  AMOUNT numeric(12,4) NOT NULL DEFAULT 0, CREATE_TIME timestamp DEFAULT now(),
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE));
COMMENT ON TABLE quickvo_demo.QS_ORDER IS '订单明细表';
CREATE TABLE quickvo_demo.QS_PRODUCT (
  ID bigserial NOT NULL, PRODUCT_NAME varchar(100) NOT NULL, PRODUCT_TYPE int DEFAULT 1,
  WEIGHT double precision, CREATED_AT timestamp(3) DEFAULT now(), CONSTRAINT PK_QS_PROD PRIMARY KEY (ID));
COMMENT ON TABLE quickvo_demo.QS_PRODUCT IS '产品表';
CREATE TABLE quickvo_demo.QS_TRADE (
  TRADE_ID varchar(32) NOT NULL, TRADE_DATE date NOT NULL, AMOUNT numeric(12,2), STATUS int DEFAULT 0,
  CONSTRAINT PK_QS_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)) PARTITION BY RANGE (TRADE_DATE);
CREATE TABLE quickvo_demo.QS_TRADE_P01 PARTITION OF quickvo_demo.QS_TRADE FOR VALUES FROM ('2026-01-01') TO ('2026-02-01');
COMMENT ON TABLE quickvo_demo.QS_TRADE IS '交易流水表';
CREATE TABLE quickvo_demo.QS_LOG (
  LOG_ID varchar(32) NOT NULL, STAFF_ID varchar(32) NOT NULL REFERENCES quickvo_demo.QS_STAFF (STAFF_ID),
  ACTION varchar(50) NOT NULL, ACTION_TIME timestamp NOT NULL, CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID));
CREATE OR REPLACE VIEW quickvo_demo.QS_V_STAFF AS SELECT STAFF_ID, STAFF_CODE FROM quickvo_demo.QS_STAFF;
