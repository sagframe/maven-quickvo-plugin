-- ClickHouse 全场景覆盖DDL(8123,无外键/无自增/无唯一索引;注释内联;默认值原生)
DROP VIEW IF EXISTS QS_V_STAFF;
DROP TABLE IF EXISTS QS_TRADE;
DROP TABLE IF EXISTS QS_LOG;
DROP TABLE IF EXISTS QS_ORDER;
DROP TABLE IF EXISTS QS_PRODUCT;
DROP TABLE IF EXISTS QS_STAFF;

CREATE TABLE QS_STAFF (
  STAFF_ID String COMMENT '员工ID',
  STAFF_CODE String COMMENT '员工工号',
  STAFF_NAME String COMMENT '员工姓名',
  SEX Int32 DEFAULT 1 COMMENT '性别:1男2女',
  BIRTHDAY Nullable(Date) COMMENT '生日',
  ENTRY_TIME Nullable(DateTime) COMMENT '入职时间',
  SALARY Nullable(Decimal(10, 2)) COMMENT '薪资',
  STATUS String DEFAULT 'A' COMMENT '状态:A在职B离职',
  BIG_REMARK String COMMENT '大文本备注(CLOB场景)',
  PHOTO String COMMENT '照片二进制(BLOB场景)',
  CREATE_TIME DateTime DEFAULT now() COMMENT '创建时间',
  LAST_MODIFIED DateTime DEFAULT now() COMMENT '最后修改时间',
  SHORT_NAME String ALIAS substring(STAFF_NAME, 1, 10) COMMENT '简称(计算列VIRTUAL)',
  TOTAL_PAY Decimal(10, 2) MATERIALIZED multiply(SALARY, 2) COMMENT '总收入(计算列STORED)'
) ENGINE = MergeTree ORDER BY STAFF_ID COMMENT '员工信息表';

CREATE TABLE QS_ORDER (
  ORDER_ID String COMMENT '订单号',
  ORDER_LINE Int32 COMMENT '订单行号',
  STAFF_ID String COMMENT '销售员工ID',
  AMOUNT Decimal(12, 4) DEFAULT 0 COMMENT '数量',
  PRICE Decimal(12, 4) DEFAULT 0 COMMENT '单价',
  CREATE_TIME DateTime DEFAULT now() COMMENT '创建时间'
) ENGINE = MergeTree ORDER BY (ORDER_ID, ORDER_LINE) COMMENT '订单明细表(复合主键=ORDER BY)';

CREATE TABLE QS_PRODUCT (
  ID Int64 COMMENT '产品ID',
  PRODUCT_NAME String COMMENT '产品名称',
  PRODUCT_TYPE Int32 DEFAULT 1 COMMENT '产品类型',
  WEIGHT Nullable(Float64) COMMENT '重量',
  SCORE Nullable(Decimal(3, 1)) DEFAULT 0 COMMENT '评分',
  CREATED_AT DateTime DEFAULT now() COMMENT '创建时间'
) ENGINE = MergeTree ORDER BY ID COMMENT '产品表';

CREATE TABLE QS_TRADE (
  TRADE_ID String COMMENT '交易ID',
  TRADE_DATE Date COMMENT '交易日期',
  AMOUNT Nullable(Decimal(12, 2)) COMMENT '交易金额',
  STATUS Int32 DEFAULT 0 COMMENT '交易状态',
  ACTION_MONTH Date COMMENT '分区月份'
) ENGINE = MergeTree PARTITION BY toYYYYMM(ACTION_MONTH) ORDER BY (TRADE_ID, TRADE_DATE) COMMENT '交易流水表(按月分区)';

CREATE TABLE QS_LOG (
  LOG_ID String COMMENT '日志ID',
  STAFF_ID String COMMENT '员工ID',
  ACTION String COMMENT '操作',
  ACTION_TIME DateTime COMMENT '操作时间'
) ENGINE = MergeTree ORDER BY LOG_ID COMMENT '操作日志表';

CREATE VIEW QS_V_STAFF AS SELECT STAFF_ID, STAFF_CODE, STAFF_NAME, SEX, STATUS FROM QS_STAFF;
