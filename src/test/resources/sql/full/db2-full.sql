COMMENT ON COLUMN SQLTOYDB.QS_PRODUCT.PRODUCT_TYPE IS '产品类型';
COMMENT ON COLUMN SQLTOYDB.QS_PRODUCT.WEIGHT IS '重量';
COMMENT ON COLUMN SQLTOYDB.QS_PRODUCT.SCORE IS '评分';
