CREATE TABLE SQLTOYDB.QS_STAFF (
  STAFF_ID VARCHAR(32) NOT NULL,
  STAFF_CODE VARCHAR(20) NOT NULL,
  STAFF_NAME VARCHAR(60) NOT NULL,
  SEX SMALLINT DEFAULT 1,
  BIRTHDAY DATE,
  ENTRY_TIME TIMESTAMP,
  SALARY DECIMAL(10,2),
  STATUS CHAR(1) DEFAULT 'A',
  BIG_REMARK CLOB,
  PHOTO BLOB,
  BONUS DECIMAL(10,2) DEFAULT 0,
  CREATE_TIME TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LAST_MODIFIED TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_QS_CODE UNIQUE (STAFF_CODE)
);
CREATE INDEX SQLTOYDB.IDX_QS_NAME ON SQLTOYDB.QS_STAFF (STAFF_NAME);
CREATE INDEX SQLTOYDB.IDX_QS_SALARY ON SQLTOYDB.QS_STAFF (SALARY);
COMMENT ON TABLE SQLTOYDB.QS_STAFF IS '员工信息表';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.STAFF_CODE IS '员工工号';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.STAFF_NAME IS '员工姓名';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.SEX IS '性别:1男2女';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.BIRTHDAY IS '生日';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.ENTRY_TIME IS '入职时间';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.SALARY IS '薪资';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.STATUS IS '状态:A在职B离职';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.BIG_REMARK IS '大文本备注(CLOB场景)';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.PHOTO IS '照片二进制(BLOB场景)';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.BONUS IS '奖金基数';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN SQLTOYDB.QS_STAFF.LAST_MODIFIED IS '最后修改时间';

CREATE TABLE SQLTOYDB.QS_ORDER (
  ORDER_ID VARCHAR(32) NOT NULL,
  ORDER_LINE INTEGER NOT NULL,
  STAFF_ID VARCHAR(32) NOT NULL,
  AMOUNT DECIMAL(12,4) NOT NULL DEFAULT 0,
  PRICE DECIMAL(12,4) NOT NULL DEFAULT 0,
  CREATE_TIME TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QS_ORDER_STAFF FOREIGN KEY (STAFF_ID) REFERENCES SQLTOYDB.QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE SQLTOYDB.QS_ORDER IS '订单明细表';
COMMENT ON COLUMN SQLTOYDB.QS_ORDER.ORDER_ID IS '订单号';
COMMENT ON COLUMN SQLTOYDB.QS_ORDER.ORDER_LINE IS '订单行号';
COMMENT ON COLUMN SQLTOYDB.QS_ORDER.STAFF_ID IS '销售员工ID';
COMMENT ON COLUMN SQLTOYDB.QS_ORDER.AMOUNT IS '数量';
COMMENT ON COLUMN SQLTOYDB.QS_ORDER.PRICE IS '单价';
COMMENT ON COLUMN SQLTOYDB.QS_ORDER.CREATE_TIME IS '创建时间';

CREATE TABLE SQLTOYDB.QS_PRODUCT (
  ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
  PRODUCT_NAME VARCHAR(100) NOT NULL,
  PRODUCT_TYPE INTEGER DEFAULT 1,
  WEIGHT DOUBLE,
  SCORE DECIMAL(3,1) DEFAULT 0.0,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_PRODUCT PRIMARY KEY (ID)
