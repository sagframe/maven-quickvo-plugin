-- 分区表:DB2 LUW范围分区(PARTITION BY RANGE,分区键须包含在唯一键/PK中);
-- quickvo经syscat.tables.npartitions/partition_mode+syscat.columns.part_key_seq提取
CREATE TABLE SQLTOYDB.QS_TRADE (
  TRADE_ID VARCHAR(32) NOT NULL,
  TRADE_DATE DATE NOT NULL,
  AMOUNT DECIMAL(12,2),
  STATUS INTEGER DEFAULT 0,
  CONSTRAINT PK_QS_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)
)
PARTITION BY RANGE (TRADE_DATE)
(PART Q1 STARTING ('2026-01-01') ENDING ('2026-02-01') EXCLUSIVE,
 PART Q2 STARTING ('2026-02-01') ENDING ('2026-03-01') EXCLUSIVE,
 PART QMAX STARTING ('2026-03-01') ENDING MAXVALUE);
COMMENT ON TABLE SQLTOYDB.QS_TRADE IS '交易流水表';
COMMENT ON COLUMN SQLTOYDB.QS_TRADE.TRADE_ID IS '交易ID';
COMMENT ON COLUMN SQLTOYDB.QS_TRADE.TRADE_DATE IS '交易日期';
COMMENT ON COLUMN SQLTOYDB.QS_TRADE.AMOUNT IS '交易金额';
COMMENT ON COLUMN SQLTOYDB.QS_TRADE.STATUS IS '交易状态';

CREATE TABLE SQLTOYDB.QS_LOG (
  LOG_ID VARCHAR(32) NOT NULL,
  STAFF_ID VARCHAR(32) NOT NULL,
  ACTION VARCHAR(50) NOT NULL,
  ACTION_TIME TIMESTAMP NOT NULL,
  CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QS_LOG_STAFF FOREIGN KEY (STAFF_ID) REFERENCES SQLTOYDB.QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE SQLTOYDB.QS_LOG IS '操作日志表';
COMMENT ON COLUMN SQLTOYDB.QS_LOG.LOG_ID IS '日志ID';
COMMENT ON COLUMN SQLTOYDB.QS_LOG.STAFF_ID IS '员工ID';
COMMENT ON COLUMN SQLTOYDB.QS_LOG.ACTION IS '操作';
COMMENT ON COLUMN SQLTOYDB.QS_LOG.ACTION_TIME IS '操作时间';
