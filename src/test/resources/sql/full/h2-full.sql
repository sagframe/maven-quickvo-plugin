DROP ALL OBJECTS;
CREATE TABLE QS_STAFF (
  STAFF_ID varchar(32) NOT NULL,
  STAFF_CODE varchar(20) NOT NULL,
  STAFF_NAME varchar(60) NOT NULL,
  SEX int DEFAULT 1,
  BIRTHDAY date,
  ENTRY_TIME timestamp(6),
  SALARY decimal(10,2),
  STATUS char(1) DEFAULT 'A',
  BIG_REMARK clob,
  PHOTO blob,
  BONUS decimal(10,2) DEFAULT 0,
  TOTAL_PAY decimal(10,2) GENERATED ALWAYS AS (SALARY + BONUS),
  CREATE_TIME timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  LAST_MODIFIED timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_QS_CODE UNIQUE (STAFF_CODE)
);
CREATE INDEX IDX_QS_NAME ON QS_STAFF (STAFF_NAME);
COMMENT ON TABLE QS_STAFF IS '员工信息表';
COMMENT ON COLUMN QS_STAFF.STAFF_ID IS '员工ID';
CREATE TABLE QS_ORDER (
  ORDER_ID varchar(32) NOT NULL,
  ORDER_LINE int NOT NULL,
  STAFF_ID varchar(32) NOT NULL,
  AMOUNT decimal(12,4) NOT NULL DEFAULT 0,
  CREATE_TIME timestamp DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QS_ORD FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE QS_ORDER IS '订单明细表';
CREATE INDEX IDX_QS_ORD_AMT ON QS_ORDER (AMOUNT, CREATE_TIME);;
CREATE TABLE QS_PRODUCT (
  ID bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  PRODUCT_NAME varchar(100) NOT NULL,
  PRODUCT_TYPE int DEFAULT 1,
  WEIGHT double,
  CREATED_AT timestamp(3) DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QS_PROD PRIMARY KEY (ID)
);
COMMENT ON TABLE QS_PRODUCT IS '产品表';
CREATE TABLE QS_LOG (
  LOG_ID varchar(32) NOT NULL,
  STAFF_ID varchar(32) NOT NULL,
  ACTION varchar(50) NOT NULL,
  ACTION_TIME timestamp NOT NULL,
  CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QS_LOG FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
);
CREATE VIEW QS_V_STAFF AS SELECT STAFF_ID, STAFF_CODE, STAFF_NAME FROM QS_STAFF;
