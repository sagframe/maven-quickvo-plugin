-- DM8 全场景覆盖DDL(5236/SYSDBA;oracle风格注释/分区/identity)
DROP TABLE SYSDBA.QS_LOG;
DROP TABLE SYSDBA.QS_TRADE;
DROP TABLE SYSDBA.QS_ORDER;
DROP TABLE SYSDBA.QS_PRODUCT;
DROP TABLE SYSDBA.QS_STAFF;

CREATE TABLE SYSDBA.QS_STAFF (
  STAFF_ID varchar(32) NOT NULL,
  STAFF_CODE varchar(20) NOT NULL,
  STAFF_NAME varchar(60) NOT NULL,
  SEX int DEFAULT 1,
  BIRTHDAY date,
  ENTRY_TIME timestamp(6),
  SALARY numeric(10,2),
  STATUS char(1) DEFAULT 'A',
  BIG_REMARK text,
  PHOTO blob,
  BONUS numeric(10,2) DEFAULT 0,
  CREATE_TIME timestamp DEFAULT SYSDATE,
  LAST_MODIFIED timestamp DEFAULT SYSDATE,
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID)
);
CREATE UNIQUE INDEX SYSDBA.UK_QS_CODE ON SYSDBA.QS_STAFF (STAFF_CODE);
CREATE INDEX SYSDBA.IDX_QS_NAME ON SYSDBA.QS_STAFF (STAFF_NAME);
CREATE INDEX SYSDBA.IDX_QS_SALARY ON SYSDBA.QS_STAFF (SALARY);
COMMENT ON TABLE SYSDBA.QS_STAFF IS '员工信息表';
COMMENT ON COLUMN SYSDBA.QS_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN SYSDBA.QS_STAFF.STAFF_CODE IS '员工工号';
COMMENT ON COLUMN SYSDBA.QS_STAFF.STAFF_NAME IS '员工姓名';
COMMENT ON COLUMN SYSDBA.QS_STAFF.SEX IS '性别:1男2女';
COMMENT ON COLUMN SYSDBA.QS_STAFF.SALARY IS '薪资';
COMMENT ON COLUMN SYSDBA.QS_STAFF.BIG_REMARK IS '大文本备注(CLOB场景)';
COMMENT ON COLUMN SYSDBA.QS_STAFF.PHOTO IS '照片二进制(BLOB场景)';
COMMENT ON COLUMN SYSDBA.QS_STAFF.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN SYSDBA.QS_STAFF.LAST_MODIFIED IS '最后修改时间';

CREATE TABLE SYSDBA.QS_ORDER (
  ORDER_ID varchar(32) NOT NULL,
  ORDER_LINE int NOT NULL,
  STAFF_ID varchar(32) NOT NULL,
  AMOUNT numeric(12,4) DEFAULT 0,
  PRICE numeric(12,4) DEFAULT 0,
  CREATE_TIME timestamp DEFAULT SYSDATE,
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QS_ORD FOREIGN KEY (STAFF_ID) REFERENCES SYSDBA.QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE SYSDBA.QS_ORDER IS '订单明细表';
COMMENT ON COLUMN SYSDBA.QS_ORDER.ORDER_ID IS '订单号';
COMMENT ON COLUMN SYSDBA.QS_ORDER.ORDER_LINE IS '订单行号';

CREATE TABLE SYSDBA.QS_PRODUCT (
  ID bigint IDENTITY(1,1) NOT NULL,
  PRODUCT_NAME varchar(100) NOT NULL,
  PRODUCT_TYPE int DEFAULT 1,
  WEIGHT double,
  SCORE numeric(3,1) DEFAULT 0.0,
  CREATED_AT timestamp DEFAULT SYSDATE,
  CONSTRAINT PK_QS_PROD PRIMARY KEY (ID)
);
COMMENT ON TABLE SYSDBA.QS_PRODUCT IS '产品表';
COMMENT ON COLUMN SYSDBA.QS_PRODUCT.ID IS '产品ID';
COMMENT ON COLUMN SYSDBA.QS_PRODUCT.PRODUCT_NAME IS '产品名称';

CREATE TABLE SYSDBA.QS_TRADE (
  TRADE_ID varchar(32) NOT NULL,
  TRADE_DATE date NOT NULL,
  AMOUNT numeric(12,2),
  STATUS int DEFAULT 0,
  CONSTRAINT PK_QS_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)
) PARTITION BY RANGE (TRADE_DATE) (
  PARTITION P202601 VALUES LESS THAN (TO_DATE('2026-02-01','YYYY-MM-DD')),
  PARTITION P202602 VALUES LESS THAN (TO_DATE('2026-03-01','YYYY-MM-DD')),
  PARTITION PMAX VALUES LESS THAN (MAXVALUE)
);
COMMENT ON TABLE SYSDBA.QS_TRADE IS '交易流水表(按月分区)';
COMMENT ON COLUMN SYSDBA.QS_TRADE.TRADE_ID IS '交易ID';
COMMENT ON COLUMN SYSDBA.QS_TRADE.TRADE_DATE IS '交易日期';

CREATE TABLE SYSDBA.QS_LOG (
  LOG_ID varchar(32) NOT NULL,
  STAFF_ID varchar(32) NOT NULL,
  ACTION varchar(50) NOT NULL,
  ACTION_TIME timestamp NOT NULL,
  CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QS_LOG FOREIGN KEY (STAFF_ID) REFERENCES SYSDBA.QS_STAFF (STAFF_ID)
);
COMMENT ON TABLE SYSDBA.QS_LOG IS '操作日志表';
COMMENT ON COLUMN SYSDBA.QS_LOG.LOG_ID IS '日志ID';
COMMENT ON COLUMN SYSDBA.QS_LOG.ACTION IS '操作';
