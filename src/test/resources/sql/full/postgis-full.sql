-- PostGIS 全场景覆盖DDL(postgis容器无pgvector,故不含向量列;5434)
CREATE SCHEMA IF NOT EXISTS quickvo_demo;

DROP VIEW IF EXISTS quickvo_demo.QS_V_STAFF;
DROP TABLE IF EXISTS quickvo_demo.QS_TRADE;
DROP TABLE IF EXISTS quickvo_demo.QS_LOG;
DROP TABLE IF EXISTS quickvo_demo.QS_ORDER;
DROP TABLE IF EXISTS quickvo_demo.QS_PRODUCT;
DROP TABLE IF EXISTS quickvo_demo.QS_STAFF;

CREATE TABLE quickvo_demo.QS_STAFF (
  STAFF_ID varchar(32) NOT NULL,
  STAFF_CODE varchar(20) NOT NULL,
  STAFF_NAME varchar(60) NOT NULL,
  SEX int DEFAULT 1,
  BIRTHDAY date,
  ENTRY_TIME timestamp(6),
  SALARY numeric(10,2),
  STATUS char(1) DEFAULT 'A',
  BIG_REMARK text,
  PHOTO bytea,
  EXT_INFO json,
  BONUS numeric(10,2) DEFAULT 0,
  TOTAL_PAY numeric(10,2) GENERATED ALWAYS AS (SALARY + BONUS) STORED,
  CREATE_TIME timestamp NOT NULL DEFAULT now(),
  LAST_MODIFIED timestamp NOT NULL DEFAULT now(),
  CONSTRAINT PK_QS_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_QS_STAFF_CODE UNIQUE (STAFF_CODE)
);
CREATE INDEX IDX_QS_STAFF_NAME ON quickvo_demo.QS_STAFF (STAFF_NAME);
CREATE INDEX IDX_QS_SALARY ON quickvo_demo.QS_STAFF (SALARY);
COMMENT ON TABLE quickvo_demo.QS_STAFF IS '员工信息表';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.STAFF_NAME IS '员工姓名';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.BIG_REMARK IS '大文本备注';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.PHOTO IS '照片二进制';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.EXT_INFO IS '扩展JSON';
COMMENT ON COLUMN quickvo_demo.QS_STAFF.TOTAL_PAY IS '总收入(计算列)';

CREATE TABLE quickvo_demo.QS_ORDER (
  ORDER_ID varchar(32) NOT NULL,
  ORDER_LINE int NOT NULL,
  STAFF_ID varchar(32) NOT NULL REFERENCES quickvo_demo.QS_STAFF (STAFF_ID),
  AMOUNT numeric(12,4) NOT NULL DEFAULT 0,
  PRICE numeric(12,4) NOT NULL DEFAULT 0,
  CREATE_TIME timestamp NOT NULL DEFAULT now(),
  CONSTRAINT PK_QS_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE)
);
COMMENT ON TABLE quickvo_demo.QS_ORDER IS '订单明细表';

CREATE TABLE quickvo_demo.QS_PRODUCT (
  ID bigserial NOT NULL,
  PRODUCT_NAME varchar(100) NOT NULL,
  PRODUCT_TYPE int DEFAULT 1,
  WEIGHT double precision,
  SCORE numeric(3,1) DEFAULT 0.0,
  CREATED_AT timestamp(3) DEFAULT now(),
  CONSTRAINT PK_QS_PRODUCT PRIMARY KEY (ID)
);
COMMENT ON TABLE quickvo_demo.QS_PRODUCT IS '产品表';

CREATE SEQUENCE quickvo_demo.SEQ_QS_TRADE;
CREATE TABLE quickvo_demo.QS_TRADE (
  TRADE_ID bigint NOT NULL DEFAULT nextval('quickvo_demo.seq_qs_trade'::regclass),
  TRADE_DATE date NOT NULL,
  AMOUNT numeric(12,2),
  STATUS int DEFAULT 0,
  CONSTRAINT PK_QS_TRADE PRIMARY KEY (TRADE_ID, TRADE_DATE)
) PARTITION BY RANGE (TRADE_DATE);
CREATE TABLE quickvo_demo.QS_TRADE_P01 PARTITION OF quickvo_demo.QS_TRADE
  FOR VALUES FROM ('2026-01-01') TO ('2026-02-01');
CREATE TABLE quickvo_demo.QS_TRADE_P02 PARTITION OF quickvo_demo.QS_TRADE
  FOR VALUES FROM ('2026-02-01') TO ('2026-03-01');
COMMENT ON TABLE quickvo_demo.QS_TRADE IS '交易流水表';
COMMENT ON COLUMN quickvo_demo.QS_TRADE.TRADE_ID IS '交易ID(sequence)';

CREATE TABLE quickvo_demo.QS_LOG (
  LOG_ID varchar(32) NOT NULL,
  STAFF_ID varchar(32) NOT NULL REFERENCES quickvo_demo.QS_STAFF (STAFF_ID),
  ACTION varchar(50) NOT NULL,
  ACTION_TIME timestamp NOT NULL,
  CONSTRAINT PK_QS_LOG PRIMARY KEY (LOG_ID)
);
COMMENT ON TABLE quickvo_demo.QS_LOG IS '操作日志表';

CREATE OR REPLACE VIEW quickvo_demo.QS_V_STAFF AS
SELECT STAFF_ID, STAFF_CODE, STAFF_NAME, SEX, STATUS FROM quickvo_demo.QS_STAFF;
