DROP VIEW IF EXISTS QS_V_STAFF;
DROP TABLE IF EXISTS QS_LOG;
DROP TABLE IF EXISTS QS_TRADE;
DROP TABLE IF EXISTS QS_ORDER;
DROP TABLE IF EXISTS QS_PRODUCT;
DROP TABLE IF EXISTS QS_STAFF;
CREATE TABLE QS_STAFF (
  STAFF_ID TEXT NOT NULL PRIMARY KEY,
  STAFF_CODE TEXT NOT NULL,
  STAFF_NAME TEXT NOT NULL,
  SEX INTEGER DEFAULT 1,
  BIRTHDAY TEXT,
  ENTRY_TIME TEXT,
  SALARY REAL,
  STATUS TEXT DEFAULT 'A',
  BIG_REMARK TEXT,
  PHOTO BLOB,
  BONUS REAL DEFAULT 0,
  TOTAL_PAY REAL GENERATED ALWAYS AS (SALARY + BONUS) STORED,
  CREATE_TIME TEXT DEFAULT (datetime('now','localtime')),
  LAST_MODIFIED TEXT DEFAULT (datetime('now','localtime'))
);
CREATE UNIQUE INDEX UK_QS_CODE ON QS_STAFF (STAFF_CODE);
CREATE INDEX IDX_QS_NAME ON QS_STAFF (STAFF_NAME);
CREATE TABLE QS_ORDER (
  ORDER_ID TEXT NOT NULL,
  ORDER_LINE INTEGER NOT NULL,
  STAFF_ID TEXT NOT NULL,
  AMOUNT REAL NOT NULL DEFAULT 0,
  CREATE_TIME TEXT DEFAULT (datetime('now','localtime')),
  PRIMARY KEY (ORDER_ID, ORDER_LINE),
  FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
);
CREATE TABLE QS_PRODUCT (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  PRODUCT_NAME TEXT NOT NULL,
  PRODUCT_TYPE INTEGER DEFAULT 1,
  WEIGHT REAL,
  CREATED_AT TEXT DEFAULT (datetime('now','localtime'))
);
CREATE TABLE QS_LOG (
  LOG_ID TEXT NOT NULL PRIMARY KEY,
  STAFF_ID TEXT NOT NULL,
  ACTION TEXT NOT NULL,
  ACTION_TIME TEXT NOT NULL,
  FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
);
CREATE VIEW QS_V_STAFF AS SELECT STAFF_ID, STAFF_CODE, STAFF_NAME FROM QS_STAFF;
