CREATE DATABASE IF NOT EXISTS test;
USE test;
DROP TABLE IF EXISTS QS_LOG;
DROP TABLE IF EXISTS QS_TRADE;
DROP TABLE IF EXISTS QS_ORDER;
DROP TABLE IF EXISTS QS_PRODUCT;
DROP TABLE IF EXISTS QS_STAFF;

CREATE TABLE QS_STAFF (
  STAFF_ID varchar(32) NOT NULL COMMENT '员工ID',
  STAFF_CODE varchar(20) NOT NULL COMMENT '员工工号',
  STAFF_NAME varchar(60) NOT NULL COMMENT '员工姓名',
  SEX tinyint DEFAULT 1 COMMENT '性别:1男2女',
  BIRTHDAY date COMMENT '生日',
  ENTRY_TIME datetime COMMENT '入职时间',
  SALARY decimal(10,2) COMMENT '薪资',
  STATUS char(1) DEFAULT 'A' COMMENT '状态:A在职B离职',
  BIG_REMARK text COMMENT '大文本备注',
  PHOTO blob COMMENT '照片二进制',
  EXT_INFO json COMMENT '扩展信息(JSON场景)',
  BONUS decimal(10,2) DEFAULT 0 COMMENT '奖金',
  TOTAL_PAY decimal(10,2) GENERATED ALWAYS AS (SALARY + BONUS) STORED COMMENT '总收入(计算列STORED)',
  SHORT_NAME varchar(30) GENERATED ALWAYS AS (left(STAFF_NAME, 10)) VIRTUAL COMMENT '简称(计算列VIRTUAL)',
  CREATE_TIME timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  LAST_MODIFIED timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '最后修改时间',
  PRIMARY KEY (STAFF_ID),
  UNIQUE KEY UK_QS_CODE (STAFF_CODE),
  KEY IDX_QS_NAME (STAFF_NAME)
) COMMENT='员工信息表';

CREATE TABLE QS_ORDER (
  ORDER_ID varchar(32) NOT NULL COMMENT '订单号',
  ORDER_LINE int NOT NULL COMMENT '订单行号',
  STAFF_ID varchar(32) NOT NULL COMMENT '销售员工ID',
  AMOUNT decimal(12,4) NOT NULL DEFAULT 0 COMMENT '数量',
  CREATE_TIME timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QS_ORD FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
) COMMENT='订单明细表';

CREATE TABLE QS_PRODUCT (
  ID bigint NOT NULL AUTO_INCREMENT COMMENT '产品ID',
  PRODUCT_NAME varchar(100) NOT NULL COMMENT '产品名称',
  PRODUCT_TYPE int DEFAULT 1 COMMENT '产品类型',
  WEIGHT double COMMENT '重量',
  CREATED_AT datetime(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  PRIMARY KEY (ID)
) COMMENT='产品表';

CREATE TABLE QS_TRADE (
  TRADE_ID varchar(32) NOT NULL COMMENT '交易ID',
  TRADE_DATE date NOT NULL COMMENT '交易日期',
  AMOUNT decimal(12,2) COMMENT '交易金额',
  STATUS int DEFAULT 0 COMMENT '交易状态',
  PRIMARY KEY (TRADE_ID, TRADE_DATE)
) COMMENT='交易流水表(按月分区)'
PARTITION BY RANGE COLUMNS(TRADE_DATE) (
  PARTITION p202601 VALUES LESS THAN ('2026-02-01'),
  PARTITION p202602 VALUES LESS THAN ('2026-03-01'),
  PARTITION pmax VALUES LESS THAN ('2027-01-01')
);

CREATE TABLE QS_LOG (
  LOG_ID varchar(32) NOT NULL COMMENT '日志ID',
  STAFF_ID varchar(32) NOT NULL COMMENT '员工ID',
  ACTION varchar(50) NOT NULL COMMENT '操作',
  ACTION_TIME datetime NOT NULL COMMENT '操作时间',
  PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QS_LOG FOREIGN KEY (STAFF_ID) REFERENCES QS_STAFF (STAFF_ID)
) COMMENT='操作日志表';

CREATE OR REPLACE VIEW QS_V_STAFF AS SELECT STAFF_ID, STAFF_CODE, STAFF_NAME, SEX, STATUS FROM QS_STAFF;
