-- sqlite(无注释语法,INTEGER PRIMARY KEY为rowid自增)
DROP TABLE IF EXISTS QUICKVO_DEMO_ORDER;
DROP TABLE IF EXISTS QUICKVO_DEMO_STAFF;
CREATE TABLE QUICKVO_DEMO_STAFF (
  STAFF_ID TEXT NOT NULL PRIMARY KEY,
  STAFF_CODE TEXT NOT NULL,
  STAFF_NAME TEXT NOT NULL,
  SEX INTEGER DEFAULT 1,
  BIRTHDAY TEXT,
  ENTRY_DATE TEXT,
  SALARY REAL
);
CREATE TABLE QUICKVO_DEMO_ORDER (
  ORDER_ID TEXT NOT NULL,
  ORDER_LINE INTEGER NOT NULL,
  STAFF_ID TEXT NOT NULL,
  AMOUNT REAL DEFAULT 0,
  CREATE_TIME TEXT,
  PRIMARY KEY (ORDER_ID, ORDER_LINE)
)
