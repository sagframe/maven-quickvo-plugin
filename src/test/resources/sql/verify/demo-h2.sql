DROP TABLE IF EXISTS QUICKVO_DEMO_ORDER;
DROP TABLE IF EXISTS QUICKVO_DEMO_STAFF;
CREATE TABLE QUICKVO_DEMO_STAFF (
  STAFF_ID varchar(32) NOT NULL,
  STAFF_CODE varchar(20) NOT NULL,
  STAFF_NAME varchar(60) NOT NULL,
  SEX int DEFAULT 1,
  BIRTHDAY date,
  ENTRY_DATE timestamp(6),
  SALARY decimal(10,2),
  STATUS char(1) DEFAULT '1',
  CONSTRAINT PK_QUICKVO_STAFF PRIMARY KEY (STAFF_ID)
);
COMMENT ON TABLE QUICKVO_DEMO_STAFF IS '员工信息表';
COMMENT ON COLUMN QUICKVO_DEMO_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN QUICKVO_DEMO_STAFF.STAFF_CODE IS '员工工号';
COMMENT ON COLUMN QUICKVO_DEMO_STAFF.STAFF_NAME IS '员工姓名';
CREATE TABLE QUICKVO_DEMO_ORDER (
  ORDER_ID varchar(32) NOT NULL,
  ORDER_LINE int NOT NULL,
  STAFF_ID varchar(32) NOT NULL,
  AMOUNT decimal(12,4) DEFAULT 0,
  CREATE_TIME timestamp(6) DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_QUICKVO_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE)
);
COMMENT ON TABLE QUICKVO_DEMO_ORDER IS '订单明细表'
