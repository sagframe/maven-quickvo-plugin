-- mysql协议兼容库(tidb/oceanbase mysql模式)
CREATE DATABASE IF NOT EXISTS quickvo_demo;
USE quickvo_demo;
DROP TABLE IF EXISTS QUICKVO_DEMO_ORDER;
DROP TABLE IF EXISTS QUICKVO_DEMO_STAFF;
CREATE TABLE QUICKVO_DEMO_STAFF (
  STAFF_ID varchar(32) NOT NULL COMMENT '员工ID',
  STAFF_CODE varchar(20) NOT NULL COMMENT '员工工号',
  STAFF_NAME varchar(60) NOT NULL COMMENT '员工姓名',
  SEX tinyint DEFAULT 1 COMMENT '性别:1男;2女',
  BIRTHDAY date COMMENT '生日',
  ENTRY_DATE datetime COMMENT '入职时间',
  SALARY decimal(10,2) COMMENT '薪资',
  PRIMARY KEY (STAFF_ID)
) COMMENT='员工信息表';
CREATE TABLE QUICKVO_DEMO_ORDER (
  ORDER_ID varchar(32) NOT NULL COMMENT '订单号',
  ORDER_LINE int NOT NULL COMMENT '订单行号',
  STAFF_ID varchar(32) NOT NULL COMMENT '销售员工ID',
  AMOUNT decimal(12,4) DEFAULT 0 COMMENT '数量',
  CREATE_TIME datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_ORDER_STAFF FOREIGN KEY (STAFF_ID) REFERENCES QUICKVO_DEMO_STAFF (STAFF_ID)
) COMMENT='订单明细表'
