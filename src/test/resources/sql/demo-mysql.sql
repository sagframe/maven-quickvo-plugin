-- quickvo golden 基线测试专用库表(容器sqltoy-mysql9,端口3307)
-- 覆盖:单主键generator策略/复合主键/自增主键/外键(导入+导出)/视图/分区表(辅助主键)/生成列/json/注释与默认值
CREATE DATABASE IF NOT EXISTS quickvo_demo DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE quickvo_demo;

DROP VIEW IF EXISTS QUICKVO_DEMO_V_STAFF;
DROP TABLE IF EXISTS QUICKVO_DEMO_TRADE;
DROP TABLE IF EXISTS QUICKVO_DEMO_STAFF_LOG;
DROP TABLE IF EXISTS QUICKVO_DEMO_ORDER;
DROP TABLE IF EXISTS QUICKVO_DEMO_PRODUCT;
DROP TABLE IF EXISTS QUICKVO_DEMO_STAFF;

-- 单主键varchar + generator策略 + 唯一索引(索引信息提取)
CREATE TABLE QUICKVO_DEMO_STAFF (
  STAFF_ID varchar(32) NOT NULL COMMENT '员工ID',
  STAFF_CODE varchar(20) NOT NULL COMMENT '员工工号',
  STAFF_NAME varchar(60) NOT NULL COMMENT '员工姓名',
  SEX tinyint DEFAULT 1 COMMENT '性别:1男;2女',
  BIRTHDAY date DEFAULT NULL COMMENT '生日',
  ENTRY_DATE datetime DEFAULT NULL COMMENT '入职时间',
  SALARY decimal(10,2) DEFAULT NULL COMMENT '薪资',
  STATUS char(1) DEFAULT '1' COMMENT '状态:1在职;2离职',
  REMARK text COMMENT '备注',
  PRIMARY KEY (STAFF_ID),
  UNIQUE KEY UK_STAFF_CODE (STAFF_CODE),
  KEY IDX_STAFF_NAME (STAFF_NAME)
) COMMENT='员工信息表';

-- 复合主键 + 外键(导入) + 默认值形态
CREATE TABLE QUICKVO_DEMO_ORDER (
  ORDER_ID varchar(32) NOT NULL COMMENT '订单号',
  ORDER_LINE int NOT NULL COMMENT '订单行号',
  STAFF_ID varchar(32) NOT NULL COMMENT '销售员工ID',
  AMOUNT decimal(12,4) NOT NULL DEFAULT 0.0000 COMMENT '数量',
  PRICE decimal(12,4) NOT NULL DEFAULT 0.0000 COMMENT '单价',
  TOTAL_AMT decimal(18,2) DEFAULT NULL COMMENT '总金额',
  CREATE_TIME timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_ORDER_STAFF FOREIGN KEY (STAFF_ID) REFERENCES QUICKVO_DEMO_STAFF (STAFF_ID)
) COMMENT='订单明细表';

-- 自增主键(identity策略) + json + 生成列
CREATE TABLE QUICKVO_DEMO_PRODUCT (
  ID bigint NOT NULL AUTO_INCREMENT COMMENT '产品ID',
  PRODUCT_NAME varchar(100) NOT NULL COMMENT '产品名称',
  PRODUCT_TYPE int DEFAULT NULL COMMENT '产品类型',
  WEIGHT double DEFAULT NULL COMMENT '重量',
  EXT_INFO json DEFAULT NULL COMMENT '扩展信息(json)',
  EXT_TAG varchar(30) GENERATED ALWAYS AS (json_unquote(json_extract(EXT_INFO, '$.tag'))) VIRTUAL COMMENT '扩展标签(生成列)',
  IS_ONLINE tinyint(1) DEFAULT 0 COMMENT '是否上架',
  CREATED_AT datetime(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  PRIMARY KEY (ID),
  KEY IDX_PRODUCT_TYPE (PRODUCT_TYPE)
) COMMENT='产品表';

-- 外键(导出/级联) + 分区表(分区键纳入主键→辅助主键)
CREATE TABLE QUICKVO_DEMO_TRADE (
  TRADE_ID varchar(32) NOT NULL COMMENT '交易ID',
  TRADE_DATE date NOT NULL COMMENT '交易日期',
  AMOUNT decimal(12,2) DEFAULT NULL COMMENT '交易金额',
  PRIMARY KEY (TRADE_ID, TRADE_DATE)
) COMMENT='交易流水表(按月分区)'
PARTITION BY RANGE (TO_DAYS(TRADE_DATE)) (
  PARTITION p202601 VALUES LESS THAN (TO_DAYS('2026-02-01')),
  PARTITION p202602 VALUES LESS THAN (TO_DAYS('2026-03-01')),
  PARTITION pmax VALUES LESS THAN MAXVALUE
);

CREATE TABLE QUICKVO_DEMO_STAFF_LOG (
  LOG_ID varchar(32) NOT NULL COMMENT '日志ID',
  STAFF_ID varchar(32) NOT NULL COMMENT '员工ID',
  OPERATE varchar(50) NOT NULL COMMENT '操作类型',
  OPERATE_TIME datetime NOT NULL COMMENT '操作时间',
  PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_LOG_STAFF FOREIGN KEY (STAFF_ID) REFERENCES QUICKVO_DEMO_STAFF (STAFF_ID)
) COMMENT='员工操作日志表';

CREATE OR REPLACE VIEW QUICKVO_DEMO_V_STAFF AS
SELECT STAFF_ID, STAFF_CODE, STAFF_NAME, SEX, STATUS FROM QUICKVO_DEMO_STAFF;
