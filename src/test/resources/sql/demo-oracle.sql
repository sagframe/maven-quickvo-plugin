CREATE TABLE SYSTEM.QUICKVO_DEMO_STAFF (
  STAFF_ID varchar2(32) NOT NULL,
  STAFF_CODE varchar2(20) NOT NULL,
  STAFF_NAME varchar2(60) NOT NULL,
  SEX number(2) DEFAULT 1,
  BIRTHDAY date,
  ENTRY_DATE timestamp(6),
  SALARY number(10,2),
  STATUS char(1) DEFAULT '1',
  REMARK clob,
  CONSTRAINT PK_QUICKVO_STAFF PRIMARY KEY (STAFF_ID),
  CONSTRAINT UK_QUICKVO_STAFF_CODE UNIQUE (STAFF_CODE)
);
COMMENT ON TABLE SYSTEM.QUICKVO_DEMO_STAFF IS '员工信息表';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.STAFF_ID IS '员工ID';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.STAFF_CODE IS '员工工号';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.STAFF_NAME IS '员工姓名';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.SEX IS '性别:1男;2女';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.BIRTHDAY IS '生日';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.ENTRY_DATE IS '入职时间';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.SALARY IS '薪资';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.STATUS IS '状态:1在职;2离职';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_STAFF.REMARK IS '备注';

CREATE TABLE SYSTEM.QUICKVO_DEMO_ORDER (
  ORDER_ID varchar2(32) NOT NULL,
  ORDER_LINE number(9) NOT NULL,
  STAFF_ID varchar2(32) NOT NULL,
  AMOUNT number(12,4) DEFAULT 0,
  PRICE number(12,4) DEFAULT 0,
  TOTAL_AMT number(18,2),
  CREATE_TIME timestamp(6) DEFAULT SYSDATE,
  CONSTRAINT PK_QUICKVO_ORDER PRIMARY KEY (ORDER_ID, ORDER_LINE),
  CONSTRAINT FK_QUICKVO_ORDER_STAFF FOREIGN KEY (STAFF_ID) REFERENCES SYSTEM.QUICKVO_DEMO_STAFF (STAFF_ID)
);
COMMENT ON TABLE SYSTEM.QUICKVO_DEMO_ORDER IS '订单明细表';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.ORDER_ID IS '订单号';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.ORDER_LINE IS '订单行号';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.STAFF_ID IS '销售员工ID';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.AMOUNT IS '数量';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.PRICE IS '单价';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.TOTAL_AMT IS '总金额';
COMMENT ON COLUMN SYSTEM.QUICKVO_DEMO_ORDER.CREATE_TIME IS '创建时间';

CREATE TABLE SYSTEM.QUICKVO_DEMO_STAFF_LOG (
  LOG_ID varchar2(32) NOT NULL,
  STAFF_ID varchar2(32) NOT NULL,
  OPERATE varchar2(50) NOT NULL,
  OPERATE_TIME timestamp(6) NOT NULL,
  CONSTRAINT PK_QUICKVO_STAFF_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT FK_QUICKVO_LOG_STAFF FOREIGN KEY (STAFF_ID) REFERENCES SYSTEM.QUICKVO_DEMO_STAFF (STAFF_ID)
);
COMMENT ON TABLE SYSTEM.QUICKVO_DEMO_STAFF_LOG IS '员工操作日志表';

CREATE OR REPLACE VIEW SYSTEM.QUICKVO_DEMO_V_STAFF AS
SELECT STAFF_ID, STAFF_CODE, STAFF_NAME, SEX, STATUS FROM SYSTEM.QUICKVO_DEMO_STAFF;
/
EXIT;
